-- ============================================================
-- 7. FUTURE STORAGE RLS DESIGN
-- ============================================================
--
-- Storage policies must validate the first segment of the
-- object path against the authenticated user's company.
--
-- Conceptually:
--
-- split_part(storage.objects.name, '/', 1)
--
-- should match:
--
-- public.current_user_company_id()::text
--
-- except for matelematics_admin.
--
--
-- IMPORTANT:
--
-- Storage INSERT / UPDATE / DELETE must NOT be granted
-- automatically to standard users.
--
-- The trusted backend should normally handle ingestion.
--
-- ============================================================


-- ============================================================
-- 8. VIDEO FILE TYPES
-- ============================================================
--
-- Final camera hardware/API selection will determine exact
-- supported formats.
--
-- Potential formats include:
--
-- video/mp4
-- video/webm
--
-- Do not enforce a definitive MIME whitelist until actual
-- camera integration requirements are verified.
--
-- ============================================================


-- ============================================================
-- 9. FILE SIZE LIMITS
-- ============================================================

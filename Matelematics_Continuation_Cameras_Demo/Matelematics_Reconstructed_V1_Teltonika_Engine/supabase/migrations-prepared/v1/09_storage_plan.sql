-- ============================================================
-- OBJECTIVE
-- ============================================================
--
-- Matelematics camera videos must NOT be stored as binary data
-- inside PostgreSQL.
--
-- Future video files will be stored in Supabase Storage.
--
-- Planned bucket:
--
--   vehicle-videos
--
-- Bucket visibility:
--
--   PRIVATE
--
-- No permanent public URLs.
--
-- Application access will use signed URLs generated by a
-- trusted backend/application layer.
--
-- ============================================================


-- ============================================================
-- 1. FUTURE BUCKET CONFIGURATION
-- ============================================================
--
-- Planned bucket:
--
--   id   = 'vehicle-videos'
--   name = 'vehicle-videos'
--   public = false
--
-- IMPORTANT:
--
-- This V1 prepared migration does NOT create the bucket.
--
-- Bucket creation will be handled in a separate controlled
-- storage migration after the core database/RLS V1 is tested.
--
-- ============================================================


-- ============================================================
-- 2. STORAGE PATH CONVENTION
-- ============================================================
--
-- Recommended object path:
--
-- company_id/
--   vehicle_id/
--     yyyy/
--       mm/
--         dd/
--           camera_id/
--             event_or_clip_id.mp4
--
-- Example:
--
-- 11111111-1111-1111-1111-111111111111/
--   22222222-2222-2222-2222-222222222222/
--     2026/
--       08/
--         30/
--           33333333-3333-3333-3333-333333333333/
--             44444444-4444-4444-4444-444444444444.mp4
--
-- ============================================================


-- ============================================================
-- 3. DATABASE RELATION
-- ============================================================
--
-- public.video_clips.storage_path
--
-- stores ONLY the Storage object path.
--
-- Example:
--
-- company_id/vehicle_id/yyyy/mm/dd/camera_id/clip_id.mp4
--
-- PostgreSQL must NOT contain the video binary itself.
--
-- ============================================================


-- ============================================================
-- 4. ACCESS MODEL
-- ============================================================
--
-- matelematics_admin
--
--   May access video objects globally according to application
--   authorization.
--
--
-- client_admin
--
--   May access video objects belonging to own company only.
--
--
-- user
--
--   May receive read access to authorized video objects from
--   own company only.
--
--   User must not automatically receive raw Storage management
--   permissions.
--
--
-- Trusted backend
--
--   Responsible for:
--
--   - uploads
--   - clip ingestion
--   - thumbnail generation
--   - signed URL creation when appropriate
--
-- ============================================================


-- ============================================================
-- 5. SIGNED URL STRATEGY
-- ============================================================
--
-- DO:
--
--   1. User requests a video clip through Matelematics.
--
--   2. Backend validates:
--
--      - authenticated user
--      - role
--      - company_id
--      - vehicle ownership
--      - clip ownership
--
--   3. Backend generates a short-lived signed URL.
--
--   4. Frontend plays/downloads the clip using that temporary
--      signed URL.
--
--
-- DO NOT:
--
--   - store permanent public URLs
--   - expose privileged Storage credentials in frontend code
--   - make bucket public
--   - trust company_id coming only from browser input
--
-- ============================================================


